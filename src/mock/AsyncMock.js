export const getProducts = ()=>{

    let error = false
    return new Promise((resolve, reject) => {
        setTimeout(() => {
            if (error) {
                reject('Error al cargar los productos')
            } else {
                resolve(productos)
            }
        },2000 )
    });
}

export const getItem = (id) => {
  return new Promise((resolve) => {
    setTimeout(() => {
      let prod = productos.find((item) => item.id === id);
      resolve(prod);
    }, 1000);
    });
}